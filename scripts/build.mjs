import { mkdir, readFile, writeFile, copyFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = path.join(root, 'dist');
await mkdir(out, { recursive: true });
// Fixed four-module build: no minifier/bundler dependency or runtime imports.
let bundle = '// Typora AutoCaps — MIT — generated by scripts/build.mjs\n';
for (const name of ['rules', 'context', 'adapter', 'main']) {
  const source = await readFile(path.join(root, 'src', `${name}.js`), 'utf8');
  bundle += `\n// src/${name}.js\n` + source.replace(/^import .*?;\r?\n/gm, '').replace(/^export (?!default)/gm, '');
}
await writeFile(path.join(out, 'main.js'), bundle);
await copyFile(path.join(root, 'manifest.json'), path.join(out, 'manifest.json'));
console.log(`Built main.js: ${(await stat(path.join(out, 'main.js'))).size} bytes. Runtime dependencies: none (host framework required).`);
